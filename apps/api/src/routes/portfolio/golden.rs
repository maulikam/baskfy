#[test]
fn pow_is_cpythons() {
    for (b, e, want) in POWS {
        let got = Dec::lit(b).pow(&Dec::lit(e)).unwrap();
        assert_eq!(got, Dec::lit(want), "{b} ** {e}");
        if want.len() > 12 {
            assert_eq!(got.to_sci_string(), *want, "{b} ** {e}");
        }
    }
}

#[test]
fn xirr_is_curated_accountings() {
    for (flows, want) in XIRRS {
        let flows: Vec<CashFlow> = flows
            .iter()
            .map(|(d, a)| CashFlow {
                on: day(d),
                amount: Dec::lit(a),
            })
            .collect();
        let got = match xirr(&flows) {
            Ok(r) => r.map(|d| d.to_sci_string()),
            Err(_) => Some("ERR".to_owned()),
        };
        assert_eq!(got.as_deref(), *want, "{flows:?}");
    }
}

#[test]
fn nav_series_are_portfolio_navs() {
    for (points, pnl, dd, md) in NAVS {
        let points: Vec<NavPoint> = points
            .iter()
            .map(|(d, v, f)| NavPoint::new(day(d), Dec::lit(v), Dec::lit(f)).unwrap())
            .collect();
        let got: Vec<(String, String, Option<String>)> = daily_pnl(&points)
            .unwrap()
            .into_iter()
            .map(|m| {
                (
                    m.on.to_string(),
                    m.amount.to_sci_string(),
                    m.pct.map(|p| p.to_sci_string()),
                )
            })
            .collect();
        let want: Vec<(String, String, Option<String>)> = pnl
            .iter()
            .map(|(d, a, p)| ((*d).to_owned(), (*a).to_owned(), p.map(str::to_owned)))
            .collect();
        assert_eq!(got, want);
        let got: Vec<[String; 4]> = drawdown_series(&points)
            .unwrap()
            .into_iter()
            .map(|p| {
                [
                    p.on.to_string(),
                    p.index.to_sci_string(),
                    p.peak.to_sci_string(),
                    p.drawdown.to_sci_string(),
                ]
            })
            .collect();
        let want: Vec<[String; 4]> = dd
            .iter()
            .map(|(a, b, c, d)| {
                [
                    (*a).to_owned(),
                    (*b).to_owned(),
                    (*c).to_owned(),
                    (*d).to_owned(),
                ]
            })
            .collect();
        assert_eq!(got, want);
        let got = max_drawdown(&points).unwrap().map(|m| {
            (
                m.peak_on.to_string(),
                m.trough_on.to_string(),
                m.drawdown.to_sci_string(),
            )
        });
        let want = md.map(|(a, b, c)| (a.to_owned(), b.to_owned(), c.to_owned()));
        assert_eq!(got, want);
    }
}
