"""Render ``benchmarks/AS-MEASURED.md`` from whatever the benchmarks recorded.

    python -m benchmarks.report            # write the table
    python -m benchmarks.report --check    # fail if any budget is unmeasured or missed

``--check`` is what CI runs after ``pytest -m benchmark``: a budget with no measurement is a
failure, because "we never measured it" and "it passes" must not look the same from the outside.
"""

from __future__ import annotations

import argparse
from collections.abc import Sequence

from benchmarks.budgets import BUDGETS, REPORT_PATH, Measurement, load_all

_HEADER = """# docs/11 — Performance budgets, as measured

<!-- GENERATED by `make bench`. Do not edit by hand. -->

Prompt 16's first acceptance criterion asks for these numbers "written into docs/11 as an
'as measured' column". The overnight working agreement that produced this file forbids editing
anything under `docs/` except appending to `docs/DECISIONS.md`, so the column is rendered here
instead, ready to be pasted into `docs/11-nonfunctional.md` by someone allowed to touch the spec.
See `docs/DECISIONS.md` §16.1.

Read the **Measured against** column before quoting any of these. A budget measured on docs/13's
single-date 271-row export is not the same claim as the same budget measured on a
2,300-instrument universe, and neither is a production p95.

"""

_TABLE_HEAD = (
    "| Surface | Target | As measured | Verdict | Method | Measured against |\n"
    "|---|---|---|---|---|---|\n"
)


def _format(measurement: Measurement) -> str:
    value = measurement.value
    if measurement.unit == "ms":
        # A sub-millisecond reading (the monitor's tick → verdict) would round to "0 ms", which
        # reads as unmeasured; three places keep it a number.
        return f"{value:.3f} ms" if value < 1 else f"{value:.0f} ms"
    if measurement.unit == "s":
        return f"{value:.2f} s"
    if measurement.unit == "min":
        return f"{value:.1f} min"
    return f"{value:.0f} KB"


def render(measurements: dict[str, Measurement]) -> str:
    lines = [_HEADER, _TABLE_HEAD]
    for budget in BUDGETS:
        found = measurements.get(budget.key)
        if found is None:
            lines.append(
                f"| {budget.surface} | {budget.target} | **not measured** | — | — "
                f"| {budget.measured_by} |\n"
            )
            continue
        verdict = {True: "PASS", False: "**MISS**", None: "n/a"}[found.within_budget]
        lines.append(
            f"| {budget.surface} | {budget.target} | {_format(found)} | {verdict} "
            f"| {found.method} | {found.dataset} |\n"
        )
    lines.append(
        "\nA row reading **not measured** means the harness named in the last column did not run "
        "or did not reach its assertion. Run `make bench` with `make up` running and "
        "`BASKFY_TEST_DATABASE_URL` exported.\n"
    )
    return "".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if a gated budget is unmeasured or missed",
    )
    parser.add_argument(
        "--gate",
        default="python",
        choices=("python", "web", "all"),
        help=(
            "which budgets --check is allowed to fail on. The Python CI job measures the "
            "server-side budgets and the web job measures the client-side ones, so each gates "
            "only what it can produce; 'all' is for a developer running `make bench` after both."
        ),
    )
    args = parser.parse_args(argv)

    measurements = load_all()
    REPORT_PATH.write_text(render(measurements), encoding="utf-8")
    print(f"wrote {REPORT_PATH.relative_to(REPORT_PATH.parents[1])}")

    if not args.check:
        return 0

    problems: list[str] = []
    for budget in BUDGETS:
        if budget.gate == "none":
            # Reported in the table as "not measured", never gated. Listed in
            # `.overnight/module-16.md` as an outstanding gap.
            continue
        if args.gate not in ("all", budget.gate):
            continue
        found = measurements.get(budget.key)
        if found is None:
            problems.append(f"{budget.key}: not measured ({budget.measured_by})")
        elif found.within_budget is False:
            problems.append(f"{budget.key}: {_format(found)} exceeds the {budget.target} budget")
    for problem in problems:
        print(f"  FAIL {problem}")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
