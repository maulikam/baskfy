const NEGATIVE: &[&str] = &["-1", "-0.01", "-4E+10", "-1E-30"];

#[test]
fn sqrt_matches_cpython_decimal() {
    let mut failures = Vec::new();
    for (operand, want) in VECTORS {
        let got = operand
            .parse::<WideDecimal>()
            .unwrap()
            .sqrt()
            .unwrap()
            .to_sci_string();
        if got != *want {
            failures.push(format!("sqrt({operand}) = {got}, CPython {want}"));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

#[test]
fn sqrt_of_a_negative_is_invalid_operation() {
    for operand in NEGATIVE {
        let err = operand.parse::<WideDecimal>().unwrap().sqrt().unwrap_err();
        assert!(err.0.contains("InvalidOperation"), "{operand}: {err:?}");
    }
}
